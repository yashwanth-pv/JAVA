/*
Definition

**Literals in Java are fixed constant values written directly in a program. They do not change during program execution and include integer, floating-point, character, string, boolean, and null literals.
In Java, **literals** are fixed values written directly in the source code. They represent constant values assigned to variables or used in expressions.

### Types of Literals in Java

1. **Integer Literals**

   * Whole numbers without a decimal point.
   * Examples:
*/
     int a = 10;
     int b = -25;
     int c = 0;

/*
2. **Floating-Point Literals**

   * Numbers with decimal points or in exponential form.
   * Examples:
*/
  
     float x = 3.14f;
     double y = 2.71828;
     double z = 1.5e3;   // 1500.0

/*
3. **Character Literals**

   * A single character enclosed in single quotes (`' '`).
   * Examples:
*/

     char ch = 'A';
     char digit = '5';
     char symbol = '@';

/*
4. **String Literals**

   * A sequence of characters enclosed in double quotes (`" "`).
   * Examples:
*/
  
     String name = "Java";
     String msg = "Hello, World!";

/*
5. **Boolean Literals**

   * Represent logical values.
   * Values:
*/
  
     boolean isJavaFun = true;
     boolean isEmpty = false;

/*
6. **Null Literal**

   * Represents the absence of a value or object reference.
   * Example:

     ```java
     String text = null;
*/
